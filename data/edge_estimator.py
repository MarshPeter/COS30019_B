# Function to extract major road names from the location string
def extract_roads(location):
    parts = location.replace('_', ' ').split()
    roads = set()
    road_types = ['RD', 'ST', 'HWY', 'GV', 'FWY', 'ARTERIAL']
    for i, part in enumerate(parts):
        if part in road_types and i > 0:
            roads.add(parts[i-1] + '_' + part)
        elif any(part.endswith('_' + rt) for rt in road_types):
             roads.add(part)
        elif i > 0 and parts[i-1] + '_' + part in location:
             roads.add(parts[i-1] + '_' + part)
    return list(roads) # Return as list for pandas apply

# Read the CSV data into a pandas DataFrame
df = pd.read_csv(io.StringIO(csv_data))

# Apply the extract_roads function to create a new column with lists of roads
df['Roads'] = df['Location'].apply(extract_roads)

# Group by SCATS and get the set of all roads for each SCATS
scats_roads = df.groupby('SCATS')['Roads'].sum().apply(set)

edges_list = []

# Iterate through all unique pairs of SCATS points and add pairs to edge_list
scats_points = scats_roads.index.tolist()
for i in range(len(scats_points)):
    for j in range(i + 1, len(scats_points)):
        scats1 = scats_points[i]
        scats2 = scats_points[j]
        # Find shared roads using set intersection
        shared_roads = scats_roads[scats1].intersection(scats_roads[scats2])
        if shared_roads:
            edge = tuple(sorted((scats1, scats2)))
            edges_list.append(edge)

# Create a DataFrame from the edges list
edges_df = pd.DataFrame(list(set(edges_list)), columns=['SCATS_A', 'SCATS_B'])

# Sort the edges for consistent output
edges_df = edges_df.sort_values(by=['SCATS_A', 'SCATS_B']).reset_index(drop=True)

